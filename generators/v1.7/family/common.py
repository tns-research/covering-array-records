def _inv5(d):
    return pow(d, 3, 5)


def mobius(a, b, c, d):
    img = []
    for x in range(6):
        if x == INF:
            num, den = a % 5, c % 5
        else:
            num, den = (a * x + b) % 5, (c * x + d) % 5
        img.append(INF if den == 0 else (num * _inv5(den)) % 5)
    return tuple(img)


def pgl25():
    G = set()
    for a, b, c, d in itertools.product(range(5), repeat=4):
        if (a * d - b * c) % 5:
            G.add(mobius(a, b, c, d))
    G = sorted(G)
    assert len(G) == 120, len(G)
    for g in G:
        assert sorted(g) == list(range(6))
    return np.array(G, dtype=np.int64)


def closure(gens, n=6):
    """group generated by permutations (tuples) of range(n)"""
    idt = tuple(range(n))
    seen = {idt}
    frontier = [idt]
    while frontier:
        nxt = []
        for h in frontier:
            for g in gens:
                p = tuple(g[h[i]] for i in range(n))
                if p not in seen:
                    seen.add(p)
                    nxt.append(p)
        frontier = nxt
    return np.array(sorted(seen), dtype=np.int64)


DIG = np.array([[(code // p) % 6 for p in (216, 36, 6, 1)] for code in range(1296)], dtype=np.int64)


def tuple_orbits(G):
    orb = -np.ones(1296, dtype=np.int64)
    sizes, nsym = [], []
    nid = 0
    for code in range(1296):
        if orb[code] >= 0:
            continue
        cs = G[:, DIG[code]] @ POW4
        orb[cs] = nid
        sizes.append(len(set(cs.tolist())))
        nsym.append(len(set(DIG[code].tolist())))
        nid += 1
    return orb, sizes, nsym


