"""Shared code for round 13 (CA(4,k,6) families), stage 1 falsification scripts.

Conventions (used by every script in this directory):
  * Symbols 0..5 = points of PG(1,5): 0..4 are GF(5) (integers mod 5), 5 is infinity.
  * PGL(2,5) = all Moebius maps x -> (a x + b)/(c x + d), ad - bc != 0 mod 5, as permutations of 0..5
    (order 120, sharply 3-transitive).
  * A 4-tuple (t0,t1,t2,t3) has code t0*216 + t1*36 + t2*6 + t3.
  * Columns 0..k-1.  Column group: Z_m with m = k - f acts on columns 0..m-1 by c -> c+1 mod m;
    columns m..k-1 (f of them) are fixed.  rho^r w is the row with (rho^r w)_c = w_{(c-r) mod m} for c < m
    and w_c for c >= m.
  * A starter w is developed into the rows { g(rho^r w) : g in PGL(2,5), r in Z_m } (duplicates removed).
    A binary starter is a starter with entries in {0,1}; its PGL-orbit is the 30 relabelings by ordered
    pairs of distinct symbols.
  * Orbits of PGL(2,5) on 4-tuples: 1 constant (size 6), 7 two-symbol (size 30), 9 "rich" (>= 3 distinct
    symbols, size 120: 6 three-symbol, 3 four-distinct).
"""
