def ca_missing(rows, t=4, v=6, stop_at=None):
    """exact check: number of missing (t-set, tuple) pairs, and the first one found"""
    rows = np.asarray(rows, dtype=np.int64)
    N, k = rows.shape
    pw = v ** np.arange(t - 1, -1, -1, dtype=np.int64)
    total, example = 0, None
    for S in itertools.combinations(range(k), t):
        codes = rows[:, list(S)] @ pw
        seen = np.zeros(v ** t, dtype=bool)
        seen[codes] = True
        miss = v ** t - int(seen.sum())
        if miss:
            total += miss
            if example is None:
                first = int(np.flatnonzero(~seen)[0])
                example = [list(S), [int(x) for x in DIG[first]]] if (t == 4 and v == 6) else [list(S), first]
            if stop_at is not None and total >= stop_at:
                break
    return total, example


def load_array(path):
    rows = []
    with open(path) as fh:
        for line in fh:
            s = line.split()
            if s:
                rows.append([int(x) for x in s])
    return np.array(rows, dtype=np.int64)


def column_classes(k, f, t=4):
    """Z_m-orbits (m = k-f) of t-subsets of columns; IDX[cls, r, j] = column of the starter read at
    position j of representative cls in the row rho^r w"""
    m = k - f

    def img(S, r):
        return tuple(sorted(((c + r) % m) if c < m else c for c in S))

    seen, reps = set(), []
    for S in itertools.combinations(range(k), t):
        if S in seen:
            continue
        seen |= {img(S, r) for r in range(m)}
        reps.append(S)
    IDX = np.array([[[((c - r) % m) if c < m else c for c in S] for r in range(m)] for S in reps],
                   dtype=np.int64)
    return reps, IDX


def rotate(w, r, m):
    w = np.asarray(w, dtype=np.int64)
    out = w.copy()
    out[:m] = np.roll(w[:m], r)
    return out


def develop(starters, k, f, include_const=True, group=None):
    if group is None:
        group = G
    m = k - f
    rows = set()
    for w in starters:
        for r in range(m):
            rw = rotate(w, r, m)
            for row in map(tuple, group[:, rw].tolist()):
                rows.add(row)
    if include_const:
        for a in range(6):
            rows.add((a,) * k)
    return np.array(sorted(rows), dtype=np.int64)


def coverage_holes(starters, k, f, need):
    """number of (class, orbit) pairs with orbit in `need` not met by the starters"""
    reps, IDX = column_classes(k, f)
    C, m = IDX.shape[0], IDX.shape[1]
    flat = IDX.reshape(C * m, 4)
    cls_of = np.repeat(np.arange(C), m)
    cnt = np.zeros(C * NORB, dtype=np.int64)
    for w in starters:
        o = ORB[np.asarray(w, dtype=np.int64)[flat] @ POW4]
        cnt += np.bincount(cls_of * NORB + o, minlength=C * NORB)
    needm = np.zeros(NORB, dtype=bool)
    needm[list(need)] = True
    return int(((cnt == 0) & np.tile(needm, C)).sum())


class StarterSearch:
    """simulated annealing over starters; cost = uncovered (class, orbit) pairs"""

    def __init__(self, k, f, n_rich, n_bin, rng, need):
        self.k, self.f, self.m = k, f, k - f
        self.reps, IDX = column_classes(k, f)
        self.C = IDX.shape[0]
        C, m = self.C, self.m
        self.flat = IDX.reshape(C * m, 4)
        self.cls_of = np.repeat(np.arange(C), m)
        self.touch = [np.flatnonzero((self.flat == c).any(axis=1)) for c in range(k)]
        needm = np.zeros(NORB, dtype=bool)
        needm[list(need)] = True
        self.need_flat = np.tile(needm, C)
        self.n_rich, self.n_bin = n_rich, n_bin
        self.ns = n_rich + n_bin
        self.alph = [6] * n_rich + [2] * n_bin
        self.rng = rng
        W = np.zeros((self.ns, k), dtype=np.int64)
        for i in range(self.ns):
            W[i] = rng.integers(0, self.alph[i], size=k)
        self.load(W)

    def load(self, W):
        self.W = np.array(W, dtype=np.int64)
        C, m = self.C, self.m
        self.O = np.zeros((self.ns, C * m), dtype=np.int64)
        self.cnt = np.zeros(C * NORB, dtype=np.int64)
        for i in range(self.ns):
            self.O[i] = ORB[self.W[i][self.flat] @ POW4]
            self.cnt += np.bincount(self.cls_of * NORB + self.O[i], minlength=C * NORB)
        self.holes = int(((self.cnt == 0) & self.need_flat).sum())

    def set_entry(self, i, c, a):
        tc = self.touch[c]
        old = self.O[i, tc]
        self.W[i, c] = a
        new = ORB[self.W[i][self.flat[tc]] @ POW4]
        base = self.cls_of[tc] * NORB
        po, pn = base + old, base + new
        aff = np.unique(np.concatenate([po, pn]))
        before = int(((self.cnt[aff] == 0) & self.need_flat[aff]).sum())
        np.subtract.at(self.cnt, po, 1)
        np.add.at(self.cnt, pn, 1)
        after = int(((self.cnt[aff] == 0) & self.need_flat[aff]).sum())
        self.O[i, tc] = new
        d = after - before
        self.holes += d
        return d

    def run(self, seconds, T0=1.0, T1=0.05, sweep=20000):
        rng = self.rng
        t_end = time.time() + seconds
        best, bestW = self.holes, self.W.copy()
        it = 0
        while self.holes > 0 and time.time() < t_end:
            if it and it % sweep == 0:
                self.load(bestW)
                for _ in range(2):  # small kick
                    i = int(rng.integers(self.ns))
                    c = int(rng.integers(self.k))
                    self.set_entry(i, c, int(rng.integers(self.alph[i])))
            T = T0 * (T1 / T0) ** ((it % sweep) / sweep)
            it += 1
            if rng.random() < 0.6:
                hp = np.flatnonzero((self.cnt == 0) & self.need_flat)
                p = int(hp[rng.integers(len(hp))])
                cls, o = divmod(p, NORB)
                if o in RICH_SET and self.n_rich > 0:
                    i = int(rng.integers(self.n_rich))
                else:
                    i = int(rng.integers(self.ns))
                r = int(rng.integers(self.m))
                c = int(self.flat[cls * self.m + r, int(rng.integers(4))])
            else:
                i = int(rng.integers(self.ns))
                c = int(rng.integers(self.k))
            A = self.alph[i]
            olda = int(self.W[i, c])
            a = int(rng.integers(A - 1))
            a = a + (a >= olda)
            d = self.set_entry(i, c, a)
            if d > 0 and rng.random() >= math.exp(-d / T):
                self.set_entry(i, c, olda)
            elif self.holes < best:
                best, bestW = self.holes, self.W.copy()
        if self.holes == 0:
            best, bestW = 0, self.W.copy()
        return best, bestW, it


def save_rows(path, rows):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as fh:
        for r in rows:
            fh.write(" ".join(str(int(x)) for x in r) + "\n")


def family_check(cid, statement, ks, f, n_rich, n_bin, total_seconds, seed=12345):
    """search witnesses for the (k, f, n_rich, n_bin) starter family; verify each witness exactly.
    A found and verified witness confirms the conjecture at that k; a miss within budget decides nothing.
    The conjecture is existential, so this script never prints 'refuted'."""
    deadline = time.time() + total_seconds
    need = TWO + RICH  # constants come from the 6 constant rows
    found, missed = {}, {}
    for idx, k in enumerate(ks):
        per = max(30.0, (deadline - time.time()) / (len(ks) - idx))
        t_k = time.time() + per
        rng = np.random.default_rng(seed + 1000 * k + f)
        att, bestholes = 0, None
        while time.time() < t_k:
            att += 1
            S = StarterSearch(k, f, n_rich, n_bin, rng, need)
            budget = max(10.0, min(per / 2, t_k - time.time()))
            best, W, it = S.run(budget)
            bestholes = best if bestholes is None else min(bestholes, best)
            log(f"{cid} k={k} f={f} attempt={att} best_holes={best} moves={it}")
            if best == 0:
                h = coverage_holes(W, k, f, need)
                rows = develop(W, k, f, include_const=True)
                miss, ex = ca_missing(rows)
                N = len(rows)
                log(f"{cid} k={k} witness N={N} formula={270 * (k - f) + 6} recheck_holes={h} missing={miss} "
                    f"live={LIVE.get(k)}")
                if miss == 0:
                    save_rows(os.path.join(OUT, f"{cid}_CA_{N}_4_{k}_6.txt"), rows)
                    with open(os.path.join(OUT, f"{cid}_k{k}_starters.json"), "w") as fh:
                        json.dump({"k": k, "f": f, "m": k - f, "starters": W.tolist(),
                                   "n_rich": n_rich, "n_bin": n_bin, "N": N}, fh)
                    found[k] = N
                else:  # cannot happen if the orbit reduction is right; report loudly
                    log(f"{cid} k={k} ORBIT REDUCTION MISMATCH: holes={h} {ex}")
                    missed[k] = f"reduction mismatch holes={h} {ex}"
                break
        if k not in found and k not in missed:
            missed[k] = f"no witness in {per:.0f}s, best holes {bestholes}"
    below = sorted(k for k, N in found.items() if N < LIVE.get(k, 10 ** 9))
    out = {"conjecture": cid, "verdict": "survives",
           "checked": f"k in {ks}, f={f}: verified witnesses for {sorted(found)}; undecided (search only) for {sorted(missed)}",
           "counterexample": None, "witness_N": {str(a): b for a, b in found.items()},
           "undecided": {str(a): b for a, b in missed.items()}, "below_live": below,
           "statement": statement}
    print(json.dumps(out), flush=True)
